import { build, transform } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { compileTokens } from './src/sienna-tokens.mjs';

const here = dirname(fileURLToPath(import.meta.url));

export const buildOptions = {
  entryPoints: [join(here, 'src', 'cli.mjs')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // ELK ships minified; re-printing it with indentation doubles the bundle, so whitespace
  // is stripped while identifiers and syntax stay readable for review.
  minify: false,
  minifyWhitespace: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'silent',
  banner: {
    js: '// Zukai CLI bundle. Generated by scripts/build.mjs from scripts/src; do not edit.\n// Third-party code and licences: see THIRD_PARTY_NOTICES.md at the repository root.',
  },
};

/** Build in memory and return the bundle text (used by the drift test). */
export async function bundleText() {
  const result = await build({ ...buildOptions, write: false });
  return Buffer.from(result.outputFiles[0].contents).toString('utf8');
}

const uiSrc = join(here, 'src', 'labs-ui');
export const uiOut = join(here, 'bin', 'labs-ui');

/** The console's modules: one browser ESM file, whitespace minified, no hashes in names. */
export const uiBuildOptions = {
  entryPoints: [join(uiSrc, 'boot.mjs')],
  bundle: true,
  platform: 'browser',
  format: 'esm',
  target: 'es2022',
  minify: false,
  minifyWhitespace: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'silent',
  write: false,
};

/** The `@font-face` rules of the console's own font files. */
function fontFaces() {
  const record = JSON.parse(readFileSync(join(uiSrc, 'fonts', 'fonts.json'), 'utf8'));
  return record.faces.map((f) => `@font-face { font-family: "${f.family}"; font-style: ${f.style}; font-weight: ${f.weight}; font-display: swap; src: url("fonts/${f.file}") format("woff2"); unicode-range: ${f.unicodeRange}; }`).join('\n');
}

/**
 * Every file of `bin/labs-ui/`, built in memory: the page, one script (Sienna's helpers, then
 * the console's modules), one stylesheet (the fonts, the compiled tokens, Sienna's stylesheet
 * without its import from Google Fonts, then the console's own layout) and the fonts with
 * their licences.
 * @returns {Promise<Map<string, Buffer>>} keyed by the path under bin/labs-ui/
 */
export async function uiFiles() {
  const files = new Map();
  const sienna = (name) => readFileSync(join(uiSrc, 'sienna', name), 'utf8');
  const siennaCss = sienna('bundle.css').replace(/^@import url\([^)]*\);\n/, '');
  if (/@import/.test(siennaCss)) throw new Error('the Sienna stylesheet still imports a stylesheet of another host');
  const css = [
    '/* Zukai Labs console. Generated by scripts/build.mjs from scripts/src/labs-ui; do not edit. */',
    fontFaces(),
    compileTokens(JSON.parse(sienna('tokens.json'))),
    siennaCss,
    readFileSync(join(uiSrc, 'app.css'), 'utf8'),
  ].join('\n');
  const minCss = (await transform(css, { loader: 'css', minifyWhitespace: true, legalComments: 'none' })).code;
  const app = await build(uiBuildOptions);
  const js = `// Zukai Labs console. Generated by scripts/build.mjs from scripts/src/labs-ui; do not edit.\n// Sienna design system helpers (src/labs-ui/sienna/bundle.js), copied unchanged:\n${sienna('bundle.js')}\n${Buffer.from(app.outputFiles[0].contents).toString('utf8')}`;
  // The page of the viewer frame takes nothing from Sienna: it holds the drawing only.
  // The script is inlined: a sandboxed page has an origin of its own, so a script it fetched
  // from the console's host would be a cross-origin response the browser blocks, and the
  // server sends no CORS header ever. The server allows this one script by its hash.
  const viewer = await build({ ...uiBuildOptions, format: 'iife', entryPoints: [join(uiSrc, 'viewer', 'viewer.mjs')] });
  const viewerJs = Buffer.from(viewer.outputFiles[0].contents).toString('utf8').replace(/<\/script/gi, '<\\/script');
  const viewerHtml = readFileSync(join(uiSrc, 'viewer', 'viewer.html'), 'utf8').replace('<script>/* viewer.mjs, inlined by build.mjs */</script>', () => `<script>${viewerJs}</script>`);
  files.set('viewer.html', Buffer.from(viewerHtml));
  // The report frame is built the same way: one inline script the server allows by its hash,
  // in a sandboxed page that fetches nothing.
  const reportFrame = await build({ ...uiBuildOptions, format: 'iife', entryPoints: [join(uiSrc, 'report-frame', 'report-frame.mjs')] });
  const reportFrameJs = Buffer.from(reportFrame.outputFiles[0].contents).toString('utf8').replace(/<\/script/gi, '<\\/script');
  const reportFrameHtml = readFileSync(join(uiSrc, 'report-frame', 'report-frame.html'), 'utf8').replace('<script>/* report-frame.mjs, inlined by build.mjs */</script>', () => `<script>${reportFrameJs}</script>`);
  files.set('report-frame.html', Buffer.from(reportFrameHtml));
  files.set('index.html', Buffer.from(readFileSync(join(uiSrc, 'index.html'), 'utf8')));
  files.set('app.css', Buffer.from(minCss));
  files.set('app.js', Buffer.from(js));
  for (const name of readdirSync(join(uiSrc, 'fonts')).sort()) {
    if (name.endsWith('.woff2') || name.endsWith('.txt')) files.set(`fonts/${name}`, readFileSync(join(uiSrc, 'fonts', name)));
  }
  return files;
}

/** Write `bin/labs-ui/` from scratch. */
export async function writeUi() {
  const files = await uiFiles();
  rmSync(uiOut, { recursive: true, force: true });
  for (const [name, bytes] of files) {
    mkdirSync(dirname(join(uiOut, name)), { recursive: true });
    writeFileSync(join(uiOut, name), bytes);
  }
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await build({ ...buildOptions, outfile: join(here, 'bin', 'cli.mjs') });
  console.log('built bin/cli.mjs');
  const files = await writeUi();
  console.log(`built bin/labs-ui (${files.size} files)`);
}
