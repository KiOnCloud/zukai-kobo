import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));

export const buildOptions = {
  entryPoints: [join(here, 'src', 'cli.mjs')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // ELK ships minified; re-printing it with indentation doubles the bundle, so whitespace
  // is stripped while identifiers and syntax stay readable for review.
  minify: false,
  minifyWhitespace: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'silent',
  banner: {
    js: '// Zukai CLI bundle. Generated by scripts/build.mjs from scripts/src; do not edit.\n// Third-party code and licences: see THIRD_PARTY_NOTICES.md at the repository root.',
  },
};

/** Build in memory and return the bundle text (used by the drift test). */
export async function bundleText() {
  const result = await build({ ...buildOptions, write: false });
  return Buffer.from(result.outputFiles[0].contents).toString('utf8');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await build({ ...buildOptions, outfile: join(here, 'bin', 'cli.mjs') });
  console.log('built bin/cli.mjs');
}
